-- Development schema source of truth. Never run this at production startup.
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT);
CREATE TABLE IF NOT EXISTS phones (
    id TEXT PRIMARY KEY, display_phone_number TEXT DEFAULT '', verified_name TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number_id TEXT NOT NULL, wa_id TEXT NOT NULL, name TEXT NOT NULL DEFAULT '',
    last_message TEXT DEFAULT '', last_message_at BIGINT DEFAULT 0,
    last_inbound_at BIGINT DEFAULT 0, unread_count INTEGER DEFAULT 0,
    history_revision INTEGER NOT NULL DEFAULT 0, UNIQUE(phone_number_id, wa_id)
);
CREATE TABLE IF NOT EXISTS messages (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id TEXT UNIQUE NOT NULL, platform_id TEXT UNIQUE, client_id TEXT UNIQUE,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id),
    direction TEXT NOT NULL, type TEXT NOT NULL, body TEXT DEFAULT '',
    caption TEXT DEFAULT '', timestamp BIGINT NOT NULL,
    status TEXT NOT NULL, filename TEXT DEFAULT '', mime_type TEXT DEFAULT '',
    attachment_path TEXT, attachment_state TEXT DEFAULT 'none', attachment_error TEXT,
    media_id TEXT, raw TEXT DEFAULT '{}', error TEXT, context_id TEXT,
    attempts INTEGER DEFAULT 0, next_attempt BIGINT DEFAULT 0
);
CREATE INDEX IF NOT EXISTS messages_conversation ON messages(conversation_id, timestamp, seq);
CREATE TABLE IF NOT EXISTS delivery (
    id TEXT PRIMARY KEY, status TEXT, timestamp BIGINT, error TEXT
);
CREATE TABLE IF NOT EXISTS deleted_messages (id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS deleted_requests (client_id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS retained_attachments (
    path TEXT PRIMARY KEY, conversation_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS login_attempts (identity TEXT, timestamp BIGINT);
CREATE TABLE IF NOT EXISTS quote_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL,
    priority TEXT NOT NULL, status TEXT NOT NULL,
    result_json TEXT NOT NULL DEFAULT '{}', selected_message_id TEXT, error TEXT DEFAULT ''
);
CREATE INDEX IF NOT EXISTS quote_evaluations_recent ON quote_evaluations(created_at DESC);
CREATE TABLE IF NOT EXISTS quote_evaluation_sources (
    evaluation_id BIGINT NOT NULL REFERENCES quote_evaluations(id) ON DELETE CASCADE,
    message_id TEXT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    position INTEGER NOT NULL, reviewed_digest TEXT,
    PRIMARY KEY (evaluation_id, message_id), UNIQUE (evaluation_id, position)
);
CREATE INDEX IF NOT EXISTS quote_sources_message ON quote_evaluation_sources(message_id);
CREATE TABLE IF NOT EXISTS archive_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT, entry TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS durable_objects (object_key TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS object_deletions (object_key TEXT PRIMARY KEY);
